// Generates xslt-extension.js, the extension's content script: content.js and
// xslt_polyfill/xslt-polyfill.min.js wrapped in one function, so neither adds
// globals to the page. Run `node scripts/bundle.mjs` after changing either.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const rootPath = fileURLToPath(root);
const polyfillDir = new URL('xslt_polyfill/', root);
const polyfillPath = fileURLToPath(polyfillDir);
const read = (file) => fs.readFileSync(new URL(file, root), 'utf8');

if (!fs.existsSync(new URL('src/libxml2/autogen.sh', polyfillDir))) {
  console.log('--- Initializing git submodules ---');
  execFileSync('git', ['submodule', 'update', '--init', '--recursive'], {
    cwd: rootPath,
    stdio: 'inherit',
  });
}

if (!fs.existsSync(new URL('node_modules', polyfillDir))) {
  console.log('--- Installing xslt_polyfill dependencies ---');
  execFileSync('npm', ['install'], {
    cwd: polyfillPath,
    stdio: 'inherit',
  });
}

console.log('--- Building xslt_polyfill ---');
execFileSync('npm', ['run', 'build'], {
  cwd: polyfillPath,
  stdio: 'inherit',
});

const polyfill = read('xslt_polyfill/xslt-polyfill.min.js');
if (!polyfill.includes('xsltPolyfillOptions')) {
  throw new Error("xslt-polyfill.min.js doesn't support xsltPolyfillOptions; update it first.");
}
fs.writeFileSync(
  new URL('xslt-extension.js', root),
  `// Generated by scripts/bundle.mjs from content.js and xslt_polyfill/xslt-polyfill.min.js. Don't edit.
(() => {
${read('content.js')}
${polyfill}
})();
`,
);
console.log('--- Built xslt-extension.js ---');
